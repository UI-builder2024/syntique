// Writes cuts/automation-pipeline.html (1080x1920, 20s). Run: node tools/build-automation.mjs
// Step times mirror shared/automation.js (they come from the voiceover word timings in shared/vo.js).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
// Voiceover carve on the music bed (EQ dips + level envelope), produced by
// hyperframes-audio/scripts/carve.mjs and saved here so rebuilds keep it.
const readCarve = (k) => {
  const f = path.join(root, `shared/carve/${k}.attrs`);
  return existsSync(f) ? " " + readFileSync(f, "utf8").trim() : "";
};
const DUR = 20;
// same beats as shared/automation.js, read from the voiceover word timings
const ctx = { window: {} };
vm.runInNewContext(readFileSync(path.join(root, "shared/vo.js"), "utf8"), ctx);
const VO = ctx.window.SYN_VO.automation;
const at = (word, from = 0) => VO.find((w, i) => i >= from && w[0].toLowerCase().startsWith(word))[1];
const CTA = +(at("content", 40) - 0.35).toFixed(2);
const STEPS = [at("researches") - 0.1, at("builds"), at("writes"), at("voices"), at("cloned") + 0.25, at("and", 28), at("reels")].map((t) => +t.toFixed(2));
const GATE = at("with");
const END = VO[VO.length - 1][2];
const LEN = { "click-soft.mp3": 0.37, "sparkle.mp3": 1.8, "whoosh.mp3": 0.57, "ping.mp3": 1.32 };

const scenes = [
  ["bg", 0, DUR, 0],
  ["a-hook", 0, 2.95, 1],
  ["a-pipe", 2.6, CTA + 0.65, 2],
  ["a-cta", CTA, DUR, 3],
  ["grain", 0, DUR, 4],
];
const sfx = [
  ...STEPS.map((t) => ["click-soft.mp3", t, 0.4]),
  ["sparkle.mp3", +(GATE + 0.4).toFixed(2), 0.22],
  ["whoosh.mp3", CTA - 0.1, 0.3],
  ["ping.mp3", +(END - 0.2).toFixed(2), 0.22],
];

const html = `<!doctype html>
<!-- Generated by tools/build-automation.mjs — edit shared/automation.js / automation.css, then re-run. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <title>Syntique — content automation pipeline</title>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <link rel="stylesheet" href="brand.css" />
    <link rel="stylesheet" href="automation.css" />
    <script src="shared/data.js"></script>
    <script src="shared/vo.js"></script>
    <script src="shared/kit.js"></script>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${DUR}" data-width="1080" data-height="1920">
${scenes.map(([id, a, b, t]) => `      <section id="${id}" class="clip" data-start="${a}" data-duration="${+(b - a).toFixed(2)}" data-track-index="${t}"></section>`).join("\n")}
      <audio id="vo" src="assets/audio/vo-automation.mp3" data-start="0" data-volume="1" data-track-index="10"></audio>
      <audio id="bed" src="assets/audio/music-automation.mp3" data-start="0" data-duration="${DUR}" data-volume="0.34" data-track-index="11"${readCarve("automation")}></audio>
${sfx.map(([f, at, v], i) => `      <audio id="sfx-${i}" src="assets/sfx/${f}" data-start="${at}" data-duration="${LEN[f]}" data-volume="${v}" data-track-index="${12 + (i % 3)}"></audio>`).join("\n")}
    </div>
    <script>
      document.getElementById("grain").innerHTML = '<div class="grain"></div>';
    </script>
    <script src="shared/automation.js"></script>
    <script>
      window.__timelines["main"] = window.SYN_TL;
    </script>
  </body>
</html>
`;
writeFileSync(path.join(root, "cuts/automation-pipeline.html"), html);
console.log("wrote cuts/automation-pipeline.html");
