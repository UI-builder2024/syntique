// Writes cuts/promo-landscape.html (1920x1080) and cuts/promo-vertical.html (1080x1920) from one template,
// so both cuts share scene windows, audio and SFX cues. Run: node tools/build-promo.mjs
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
// Voiceover carve on the music bed (EQ dips + level envelope), produced by
// hyperframes-audio/scripts/carve.mjs and saved here so rebuilds keep it.
const readCarve = (k) => {
  const f = path.join(root, `shared/carve/${k}.attrs`);
  return existsSync(f) ? " " + readFileSync(f, "utf8").trim() : "";
};
const DUR = 45;

// [id, start, end, track, extra class]
const SCENES = [
  ["bg", 0, DUR, 0],
  ["s-hook", 0, 4.65, 1],
  ["s-sting", 4.5, 7.9, 2],
  ["s-pos", 7.85, 15.9, 1],
  ["s-case-1", 15.3, 21.45, 2, "case"],
  ["s-case-2", 20.85, 25.65, 3, "case"],
  ["s-case-3", 25.05, 29.4, 2, "case"],
  ["s-case-4", 28.8, 33.9, 3, "case"],
  ["s-case-5", 33.3, 38.3, 2, "case"],
  ["s-proc", 37.75, 41.7, 3],
  ["s-cta", 41.05, DUR, 4],
  ["hud", 0, DUR, 5],
  ["grain", 0, DUR, 6],
];

// [id, file, start, volume]
export const SFX_LEN = { "impact-bass-1.mp3": 2.12, "impact-bass-2.mp3": 2.59, "whoosh-short.mp3": 0.57, "whoosh.mp3": 0.57, "pop.mp3": 0.72, "ping.mp3": 1.32, "click-soft.mp3": 0.37, "chime.mp3": 2.5, "sparkle.mp3": 1.8, "key-press.mp3": 0.4, "notification.mp3": 2.46 };
const SFX = [
  ["sfx-impact", "impact-bass-1.mp3", 4.84, 0.5],
  ["sfx-w1", "whoosh-short.mp3", 15.2, 0.35],
  ["sfx-w2", "whoosh-short.mp3", 20.75, 0.35],
  ["sfx-w3", "whoosh-short.mp3", 24.95, 0.35],
  ["sfx-w4", "whoosh-short.mp3", 28.7, 0.35],
  ["sfx-w5", "whoosh-short.mp3", 33.2, 0.35],
  ["sfx-pop1", "pop.mp3", 12.5, 0.25],
  ["sfx-pop2", "pop.mp3", 13.3, 0.25],
  ["sfx-pop3", "pop.mp3", 14.02, 0.25],
  ["sfx-w6", "whoosh.mp3", 37.65, 0.3],
  ["sfx-cta", "impact-bass-2.mp3", 40.95, 0.4],
  ["sfx-ping", "ping.mp3", 42.9, 0.25],
];

function page(orient, w, h) {
  const scenes = SCENES.map(
    ([id, a, b, track, cls]) =>
      `      <section id="${id}" class="clip${cls ? " " + cls : ""}" data-start="${a}" data-duration="${+(b - a).toFixed(2)}" data-track-index="${track}"></section>`
  ).join("\n");
  const sfx = SFX.map(
    ([id, f, at, v], i) =>
      `      <audio id="${id}" src="assets/sfx/${f}" data-start="${at}" data-duration="${SFX_LEN[f]}" data-volume="${v}" data-track-index="${12 + (i % 3)}"></audio>`
  ).join("\n");
  return `<!doctype html>
<!-- Generated by tools/build-promo.mjs — edit the template there, then re-run. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${w}, height=${h}" />
    <title>Syntique — brand promo ${orient === "vert" ? "9:16" : "16:9"}</title>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <link rel="stylesheet" href="brand.css" />
    <link rel="stylesheet" href="promo.css" />
    <script src="shared/data.js"></script>
    <script src="shared/vo.js"></script>
    <script src="shared/kit.js"></script>
  </head>
  <body>
    <div id="root" class="${orient}" data-orient="${orient}" data-composition-id="main" data-start="0" data-duration="${DUR}" data-width="${w}" data-height="${h}">
${scenes}
      <audio id="vo" src="assets/audio/vo-promo.mp3" data-start="0" data-volume="1" data-track-index="10"></audio>
      <audio id="bed" src="assets/audio/music-promo.mp3" data-start="0" data-duration="${DUR}" data-volume="0.32" data-track-index="11"${readCarve("promo")}></audio>
${sfx}
    </div>
    <script>
      document.getElementById("grain").innerHTML = '<div class="grain"></div>';
    </script>
    <script src="shared/promo.js"></script>
    <script>
      window.__timelines["main"] = window.SYN_TL;
    </script>
  </body>
</html>
`;
}

writeFileSync(path.join(root, "cuts/promo-landscape.html"), page("land", 1920, 1080));
writeFileSync(path.join(root, "cuts/promo-vertical.html"), page("vert", 1080, 1920));
console.log("wrote cuts/promo-landscape.html, cuts/promo-vertical.html");
