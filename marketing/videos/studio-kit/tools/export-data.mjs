// Exports the site's own copy and facts (src/lib/*.ts) to shared/data.js so the
// videos never retype a stat. Re-run after editing work.ts / services.ts / site.ts:
//   node --experimental-strip-types tools/export-data.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const lib = path.resolve(here, "../../../../src/lib");
const load = (f) => import(pathToFileURL(path.join(lib, f)).href);

const { PROJECTS } = await load("work.ts");
const { SERVICES } = await load("services.ts");
const { SITE } = await load("site.ts");

const host = new URL(SITE.url).host;
const data = {
  site: { name: SITE.name, short: SITE.short, tagline: SITE.tagline, host, email: SITE.email, availability: SITE.availability },
  projects: PROJECTS.map((p) => ({
    slug: p.slug,
    name: p.name,
    client: p.client,
    region: p.region,
    category: p.category,
    urlLabel: p.urlLabel,
    dir: p.images.hero.split("/")[2],
    headline: p.headline,
    accent: p.accent,
    accentInk: p.accentInk,
    stats: p.stats,
    approach: p.approach.map((a) => a.title),
    stack: p.stack,
    services: p.services,
  })),
  services: SERVICES.map((s) => ({ slug: s.slug, name: s.name, short: s.short })),
};

const out = path.resolve(here, "../shared/data.js");
writeFileSync(out, `// Generated by tools/export-data.mjs from src/lib/*.ts — do not edit by hand.\nwindow.SYN_DATA = ${JSON.stringify(data, null, 2)};\n`);
console.log("wrote", out, data.projects.length, "projects");
