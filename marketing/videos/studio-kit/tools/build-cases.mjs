// Writes cuts/case-<slug>.html for every project in src/lib/work.ts (via shared/data.js).
// Run: node tools/build-cases.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ctx = { window: {} };
vm.runInNewContext(readFileSync(path.join(root, "shared/data.js"), "utf8"), ctx);
const { projects } = ctx.window.SYN_DATA;

const DUR = 16;
const T = { b: 3.37, c: 7.46, d: 10.52, e: 12.57 };
const LEN = { "whoosh-short.mp3": 0.57, "click-soft.mp3": 0.37, "ping.mp3": 1.32, "impact-bass-1.mp3": 2.12 };

for (const p of projects) {
  const scenes = [
    ["c-hook", 0, T.b + 0.5, 1],
    ["c-dev", T.b - 0.12, T.c + 0.5, 2],
    ["c-did", T.c - 0.12, T.d + 0.5, 1],
    ["c-stats", T.d - 0.12, T.e + 0.38, 2],
    ["c-cta", T.e - 0.12, DUR, 3],
    ["hud", 0, DUR, 4],
    ["grain", 0, DUR, 5],
  ];
  const sfx = [
    ["whoosh-short.mp3", T.b - 0.15, 0.3],
    ["whoosh-short.mp3", T.c - 0.15, 0.3],
    ["whoosh-short.mp3", T.d - 0.15, 0.3],
    ["whoosh-short.mp3", T.e - 0.15, 0.3],
    ...p.approach.map((_, i) => ["click-soft.mp3", +(T.c + 0.5 + i * Math.min(0.5, 2 / p.approach.length)).toFixed(2), 0.35]),
    ["ping.mp3", T.e + 1.2, 0.22],
  ];
  const html = `<!doctype html>
<!-- Generated by tools/build-cases.mjs — edit shared/case.js / case.css, then re-run. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <title>Syntique — case study: ${p.name}</title>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <link rel="stylesheet" href="brand.css" />
    <link rel="stylesheet" href="case.css" />
    <script src="shared/data.js"></script>
    <script src="shared/kit.js"></script>
  </head>
  <body>
    <div id="root" data-slug="${p.slug}" data-composition-id="main" data-start="0" data-duration="${DUR}" data-width="1080" data-height="1920">
${scenes.map(([id, a, b, t]) => `      <section id="${id}" class="clip" data-start="${+a.toFixed(2)}" data-duration="${+(b - a).toFixed(2)}" data-track-index="${t}"></section>`).join("\n")}
      <audio id="bed" src="assets/audio/music-case.mp3" data-start="0" data-duration="${DUR}" data-volume="0.85" data-track-index="10"></audio>
${sfx.map(([f, at, v], i) => `      <audio id="sfx-${i}" src="assets/sfx/${f}" data-start="${at}" data-duration="${LEN[f]}" data-volume="${v}" data-track-index="${11 + (i % 3)}"></audio>`).join("\n")}
    </div>
    <script>
      document.getElementById("grain").innerHTML = '<div class="grain"></div>';
    </script>
    <script src="shared/case.js"></script>
    <script>
      window.__timelines["main"] = window.SYN_TL;
    </script>
  </body>
</html>
`;
  writeFileSync(path.join(root, `cuts/case-${p.dir}.html`), html);
  console.log(`wrote cuts/case-${p.dir}.html`);
}
